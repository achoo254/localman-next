import { z } from "zod";
import { toMcpToolDescriptor } from "./mcp-tool-descriptor.js";
import {
	type AnyOperation,
	DEFAULT_TOOLSETS,
	TOOLSETS,
	type Toolset,
} from "./types.js";

function isRecord(value: unknown): value is Record<string, unknown> {
	return typeof value === "object" && value !== null;
}

/**
 * Narrows a loaded registry entry to an operation built by
 * `defineOperation` (CI loads registries as untyped modules).
 */
export function isOperationDefinition(value: unknown): value is AnyOperation {
	return (
		isRecord(value) &&
		typeof value.id === "string" &&
		typeof value.method === "string" &&
		typeof value.path === "string" &&
		typeof value.toolset === "string" &&
		typeof value.dryRun === "boolean" &&
		typeof value.createsCredential === "boolean" &&
		typeof value.requiresConfirmation === "boolean" &&
		typeof value.handler === "function" &&
		Array.isArray(value.scopes) &&
		isRecord(value.annotations) &&
		value.mcp !== undefined &&
		value.input instanceof z.ZodObject &&
		value.output instanceof z.ZodType
	);
}

/** Markdown table cells cannot contain raw pipes or line breaks. */
function cell(text: string): string {
	return text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
}

function hintsOf(op: AnyOperation): string {
	const hints: string[] = [];
	if (op.annotations.readOnly) hints.push("read-only");
	if (op.annotations.destructive) hints.push("destructive");
	if (op.annotations.idempotent) hints.push("idempotent");
	return hints.length > 0 ? hints.join(", ") : "write";
}

function toolRows(ops: readonly AnyOperation[]): string[] {
	const rows: string[] = [];
	for (const op of ops) {
		const tool = toMcpToolDescriptor(op);
		if (!tool) continue;
		const confirm = tool.requiresConfirmation
			? "`dry_run` then `confirm_token`"
			: tool.dryRun
				? "`dry_run` optional"
				: "—";
		const scopes = tool.scopes.map((scope) => `\`${scope}\``).join(", ");
		rows.push(
			`| \`${tool.name}\` | \`${op.id}\` | \`${op.method} ${op.path}\` | ${hintsOf(op)} | ${scopes} | ${confirm} | ${cell(op.summary ?? tool.description)} |`,
		);
	}
	return rows;
}

function exemptRows(ops: readonly AnyOperation[]): string[] {
	return ops.flatMap((op) =>
		op.mcp === true
			? []
			: [
					`| \`${op.id}\` | \`${op.method} ${op.path}\` | ${cell(op.mcp.exempt)} |`,
				],
	);
}

function toolsetSection(
	toolset: Toolset,
	ops: readonly AnyOperation[],
): string {
	const lines = [`## Toolset \`${toolset}\``, ""];
	const tools = toolRows(ops);
	if (tools.length > 0) {
		lines.push(
			"| Tool | Operation | REST | Hints | Token scopes | Confirmation | Summary |",
			"|---|---|---|---|---|---|---|",
			...tools,
			"",
		);
	}
	const exempt = exemptRows(ops);
	if (exempt.length > 0) {
		lines.push(
			"No MCP tool (exempt):",
			"",
			"| Operation | REST | Reason |",
			"|---|---|---|",
			...exempt,
			"",
		);
	}
	return lines.join("\n");
}

/**
 * Markdown table of operation → MCP tool, one section per toolset, for
 * CI output and the "MCP tools" docs page.
 */
export function renderMcpToolTable(
	operations: readonly AnyOperation[],
): string {
	const defaults = DEFAULT_TOOLSETS.map((name) => `\`${name}\``).join(", ");
	const sections = TOOLSETS.flatMap((toolset) => {
		const ops = operations.filter((op) => op.toolset === toolset);
		return ops.length > 0 ? [toolsetSection(toolset, ops)] : [];
	});
	return [
		"# MCP tools",
		"",
		"Generated by `pnpm check:mcp-coverage --markdown <path>` from the operation registry; do not edit by hand.",
		"",
		`Toolsets enabled by default: ${defaults}. Choose others with \`?toolsets=a,b\` or the \`list_toolsets\` and \`enable_toolset\` tools.`,
		"",
		...sections,
	].join("\n");
}
