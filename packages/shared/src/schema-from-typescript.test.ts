import { describe, expect, it } from "vitest";
import { isFakerMethodId } from "./faker-method-catalog.js";
import { resourceFieldsSchema } from "./resource-schema.js";
import { schemaFromTypeScript } from "./schema-from-typescript.js";
import type { SchemaImportResult } from "./schema-import-fields.js";

const USER = `
/** A registered user. */
export interface User {
	id: string; // generated by Localman
	readonly email: string;
	avatar?: string;
	fullName: string;
	age: number;
	isActive: boolean;
	createdAt: Date;
	updated_at: string;
	role: "admin" | "member" | "guest";
	tags: string[];
	scores: Array<number>;
	address: { street: string; city: string } | null;
	/* nested block comment */
	meta: Record<string, unknown>;
	lat: number;
}`;

function fieldsOf(result: SchemaImportResult) {
	if (!result.ok)
		throw new Error(`${result.error.code}: ${result.error.message}`);
	expect(resourceFieldsSchema.safeParse(result.fields).success).toBe(true);
	return result.fields;
}

describe("schemaFromTypeScript", () => {
	it("maps an interface to Localman fields with Faker hints", () => {
		const result = schemaFromTypeScript(USER);
		expect(fieldsOf(result)).toMatchSnapshot();
		expect(result.ok && result.name).toBe("User");
		expect(result.ok && result.warnings).toMatchSnapshot();
	});

	it("resolves aliases, extends, intersections and picks by name", () => {
		const source = `
			type Status = "draft" | "published";
			type Count = 1 | 2 | 3;
			interface Base { createdAt: Date; title: string }
			interface Post extends Base { status: Status; views: Count; author: Author }
			interface Author { name: string }
			type Draft = Post & { notes?: string; title: number };
		`;
		const post = schemaFromTypeScript(source, { name: "Post" });
		expect(fieldsOf(post).map((f) => `${f.name}:${f.type}`)).toEqual([
			"createdAt:Date",
			"title:Faker.js",
			"status:String",
			"views:Number",
			"author:Object",
		]);
		const draft = fieldsOf(schemaFromTypeScript(source, { name: "Draft" }));
		expect(draft.find((f) => f.name === "title")?.type).toBe("Number");
		expect(draft.map((f) => f.name)).toContain("notes");
		// No name: the first object type (Base) is used.
		const first = schemaFromTypeScript(source);
		expect(first.ok && first.name).toBe("Base");
	});

	it("handles recursive and repeated aliases without blowing up", () => {
		const tree =
			"interface Node { label: string; children: Node[]; parent?: Node }";
		expect(fieldsOf(schemaFromTypeScript(tree))).toHaveLength(3);
		const loop = "type A = B; type B = A | string; interface X { a: A; b: B }";
		expect(fieldsOf(schemaFromTypeScript(loop))).toHaveLength(2);
		const bomb = ["type T0 = string;"];
		for (let i = 1; i < 40; i += 1) {
			bomb.push(
				`type T${i} = ${Array(8)
					.fill(`T${i - 1}`)
					.join(" | ")};`,
			);
		}
		bomb.push("interface X { value: T39 }");
		const started = Date.now();
		expect(fieldsOf(schemaFromTypeScript(bomb.join("\n")))[0]?.type).toBe(
			"String",
		);
		expect(Date.now() - started).toBeLessThan(1000);
	});

	it("only suggests whitelisted Faker methods of the right type", () => {
		const names = [
			"email",
			"avatar",
			"photoUrl",
			"website",
			"username",
			"password",
			"firstName",
			"last_name",
			"name",
			"jobTitle",
			"phone",
			"address",
			"city",
			"country",
			"zipCode",
			"state",
			"company",
			"title",
			"bio",
			"description",
			"uuid",
			"color",
			"slug",
			"ip",
			"currency",
			"gender",
			"birthdate",
			"publishedAt",
		];
		const members = names.map((name) => `${name}: string;`).join(" ");
		const fields = fieldsOf(
			schemaFromTypeScript(
				`interface X { ${members} lat: number; price: number }`,
			),
		);
		for (const field of fields.slice(0, names.length)) {
			expect(field.type, field.name).toBe("Faker.js");
			expect(isFakerMethodId(field.fakerMethod ?? ""), field.name).toBe(true);
		}
		expect(fields.at(-1)).toEqual({ name: "price", type: "Number" });
	});
});
