import { parentKeyOf } from "@localman/shared/constants";
import {
	type TreeItem,
	orderTree,
} from "../../features/resource-tree/tree-layout";

export type EndpointMethod = "GET" | "POST" | "PUT" | "DELETE";

export interface EndpointLine {
	readonly methods: readonly EndpointMethod[];
	readonly path: string;
}

export interface EndpointGroup {
	readonly name: string;
	readonly lines: readonly EndpointLine[];
}

const COLLECTION: readonly EndpointMethod[] = ["GET", "POST"];
const ITEM: readonly EndpointMethod[] = ["GET", "PUT", "DELETE"];

/** `/{base}` and `/{base}/:id` with their CRUD methods. */
function crudLines(base: string): EndpointLine[] {
	return [
		{ methods: COLLECTION, path: base },
		{ methods: ITEM, path: `${base}/:id` },
	];
}

/**
 * Endpoints generated by a resource tree, as listed by the landing demo.
 * Groups go by depth, then tree order (parent before child, older sibling
 * first). A root resource has `/{name}` and `/{name}/:id` (5 endpoints); a
 * nested one adds `/{parent}/:{parentKey}/{name}` and its `/:id` (10).
 * The runtime also accepts the longer ancestor chain; the demo lists only
 * the direct-parent form, like the source.
 */
export function endpointGroups(items: readonly TreeItem[]): EndpointGroup[] {
	const byId = new Map(items.map((item) => [item.id, item]));
	const ordered = orderTree(items).map((entry, index) => ({ ...entry, index }));
	ordered.sort((a, b) => a.depth - b.depth || a.index - b.index);
	return ordered.map(({ item }) => {
		const parent = item.parentId === null ? undefined : byId.get(item.parentId);
		const lines = crudLines(`/${item.name}`);
		if (parent) {
			lines.push(
				...crudLines(
					`/${parent.name}/:${parentKeyOf(parent.name)}/${item.name}`,
				),
			);
		}
		return { name: item.name, lines };
	});
}

/** Number of method + path pairs across all groups. */
export function endpointCount(groups: readonly EndpointGroup[]): number {
	return groups.reduce(
		(sum, group) =>
			sum +
			group.lines.reduce((lineSum, line) => lineSum + line.methods.length, 0),
		0,
	);
}

/** Seed of the demo (`seedLanding`): users › posts; comments, likes at root. */
export const RELATIONS_SEED: readonly TreeItem[] = Object.freeze([
	{ id: "users", parentId: null, name: "users" },
	{ id: "posts", parentId: "users", name: "posts" },
	{ id: "comments", parentId: null, name: "comments" },
	{ id: "likes", parentId: null, name: "likes" },
]);
