/**
 * Exports the records of a resource tree as TypeScript interfaces or Zod
 * schemas (source code strings for the user to copy). Both describe what
 * the mock API returns; see `type-export-model.ts` for the record shapes.
 * The Zod output runs on Zod 3 and 4 (`z.object`, `.extend`, two-argument
 * `z.record`) and needs no recursion: embedded records are `…Record`
 * schemas, which hold no relation fields.
 */
import type { TypeField, TypeNode } from "./type-export-fields.js";
import {
	type ResourceTypeModel,
	type TypeExportResource,
	buildTypeModels,
} from "./type-export-model.js";

export type { TypeExportResource } from "./type-export-model.js";

const HEADER = "// Generated by Localman from the project's resources.";
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

/** A property key: bare when it is an identifier, else a quoted string. */
function propertyKey(key: string): string {
	return IDENTIFIER.test(key) ? key : JSON.stringify(key);
}

function indent(depth: number): string {
	return "\t".repeat(depth);
}

// ---------------------------------------------------------------- TypeScript

function tsType(node: TypeNode, depth: number): string {
	switch (node.kind) {
		case "string":
		case "number":
		case "boolean":
		case "null":
		case "unknown":
			return node.kind;
		case "dict":
			return "{ [key: string]: unknown }";
		case "ref":
			return node.name;
		case "array": {
			const item = tsType(node.item, depth);
			return node.item.kind === "union" ? `(${item})[]` : `${item}[]`;
		}
		case "union":
			return node.options.map((option) => tsType(option, depth)).join(" | ");
		case "object":
			return `{\n${tsMembers(node.fields, depth + 1)}${indent(depth)}}`;
	}
}

function tsMembers(fields: readonly TypeField[], depth: number): string {
	return fields
		.map((field) => {
			const note = field.note ? `${indent(depth)}/** ${field.note} */\n` : "";
			const type = tsType(field.type, depth);
			return `${note}${indent(depth)}${propertyKey(field.key)}: ${type};\n`;
		})
		.join("");
}

function tsInterfaces(model: ResourceTypeModel): string {
	const own = `Record of the "${model.resourceName}" resource`;
	if (model.recordName === null) {
		return `/** ${own}. */\nexport interface ${model.typeName} {\n${tsMembers(model.stored, 1)}}\n`;
	}
	return [
		`/** ${own}, as embedded by a related resource. */`,
		`export interface ${model.recordName} {\n${tsMembers(model.stored, 1)}}`,
		"",
		`/** ${own}, with its relation fields. */`,
		`export interface ${model.typeName} extends ${model.recordName} {\n${tsMembers(model.relations, 1)}}`,
		"",
	].join("\n");
}

/** One interface per resource (two when it has relation fields). */
export function exportTypeScript(
	resources: readonly TypeExportResource[],
): string {
	const blocks = buildTypeModels(resources).map(tsInterfaces);
	return [HEADER, "", ...blocks].join("\n");
}

// ----------------------------------------------------------------------- Zod

function schemaName(typeName: string): string {
	return `${typeName.charAt(0).toLowerCase()}${typeName.slice(1)}Schema`;
}

function zodType(node: TypeNode, depth: number): string {
	switch (node.kind) {
		case "string":
		case "number":
		case "boolean":
		case "null":
		case "unknown":
			return `z.${node.kind}()`;
		case "dict":
			return "z.record(z.string(), z.unknown())";
		case "ref":
			return schemaName(node.name);
		case "array":
			return `z.array(${zodType(node.item, depth)})`;
		case "union": {
			// Options are distinct, so one non-null option means `T | null`.
			const others = node.options.filter((option) => option.kind !== "null");
			const [only] = others;
			if (only !== undefined && others.length === 1) {
				return `${zodType(only, depth)}.nullable()`;
			}
			const options = node.options.map((option) => zodType(option, depth));
			return `z.union([${options.join(", ")}])`;
		}
		case "object":
			return `z.object({\n${zodMembers(node.fields, depth + 1)}${indent(depth)}})`;
	}
}

function zodMembers(fields: readonly TypeField[], depth: number): string {
	return fields
		.map(
			(field) =>
				`${indent(depth)}${propertyKey(field.key)}: ${zodType(field.type, depth)},\n`,
		)
		.join("");
}

function zodSchema(typeName: string, body: string): string {
	const name = schemaName(typeName);
	return `export const ${name} = ${body};\nexport type ${typeName} = z.infer<typeof ${name}>;\n`;
}

/** Records first, so every schema is defined before it is referenced. */
export function exportZodSchemas(
	resources: readonly TypeExportResource[],
): string {
	const models = buildTypeModels(resources);
	const records = models.map((model) =>
		zodSchema(
			model.recordName ?? model.typeName,
			`z.object({\n${zodMembers(model.stored, 1)}})`,
		),
	);
	const related = models.flatMap((model) =>
		model.recordName === null
			? []
			: [
					zodSchema(
						model.typeName,
						`${schemaName(model.recordName)}.extend({\n${zodMembers(model.relations, 1)}})`,
					),
				],
	);
	return [HEADER, 'import { z } from "zod";', "", ...records, ...related]
		.join("\n")
		.replace(/\n+$/, "\n");
}
